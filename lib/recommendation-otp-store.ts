
/**
 * MBY Studio — Recommendation OTP atomic storage
 * R2.21-I.8.3 | Supabase Test / local development
 *
 * Redis Lua operations for OTP challenge creation and
 * verification. No public endpoints or email delivery.
 *
 * Only server-generated identifiers, keys and fingerprints
 * may be supplied by the future calling service.
 */

import "server-only";

import {
  RECOMMENDATION_EMAIL_VERIFICATION as config,
} from "./recommendation-email-verification-config";

import {
  executeRecommendationOtpScript,
} from "./recommendation-otp-redis";

/**
 * A challenge is stored with a fingerprint and an
 * attempt counter. Redis applies the expiration.
 *
 * SET NX ensures an existing challenge cannot be
 * overwritten accidentally.
 */
const CREATE_CHALLENGE_SCRIPT = `
  if redis.call('EXISTS', KEYS[1]) == 1 then
    return 0
  end

  redis.call(
    'HSET',
    KEYS[1],
    'fingerprint', ARGV[1],
    'attempts', 0
  )

  redis.call('EXPIRE', KEYS[1], tonumber(ARGV[2]))

  return 1
`;

/**
 * Atomically checks a submitted fingerprint.
 *
 * Results:
 *   1 = verified; challenge consumed
 *   0 = incorrect; attempt counted
 *  -1 = missing or expired
 *  -2 = maximum attempts reached
 *
 * The fingerprint is a server-generated HMAC.
 * Redis never receives the plaintext OTP.
 */
const VERIFY_CHALLENGE_SCRIPT = `
  if redis.call('EXISTS', KEYS[1]) == 0 then
    return -1
  end

  local attempts = tonumber(
    redis.call('HGET', KEYS[1], 'attempts') or '0'
  )

  local maxAttempts = tonumber(ARGV[2])

  if attempts >= maxAttempts then
    redis.call('DEL', KEYS[1])
    return -2
  end

  local expected = redis.call(
    'HGET', KEYS[1], 'fingerprint'
  )

  if expected == ARGV[1] then
    redis.call('DEL', KEYS[1])
    return 1
  end

  attempts = redis.call('HINCRBY', KEYS[1], 'attempts', 1)

  if attempts >= maxAttempts then
    redis.call('DEL', KEYS[1])
    return -2
  end

  return 0
`;

export type OtpVerificationResult =
  | "verified"
  | "incorrect"
  | "expired"
  | "locked"
  | "unavailable";

/**
 * Store a new OTP challenge.
 *
 * The key and fingerprint must be generated by trusted
 * server code; they must never contain plaintext email
 * addresses, OTPs or other personal information.
 */
export async function createRecommendationOtpChallenge(
  key: string,
  fingerprint: string
): Promise<boolean> {
  if (
    !key.startsWith(`${config.redisPrefix}:challenge:`) ||
    !/^[a-f0-9]{64}$/.test(fingerprint)
  ) {
    return false;
  }

  const response = await executeRecommendationOtpScript(
    CREATE_CHALLENGE_SCRIPT,
    [key],
    [fingerprint, String(config.expiresInSeconds)]
  );

  return response.ok && response.result === 1;
}

/**
 * Verify and consume an OTP challenge atomically.
 */
export async function verifyRecommendationOtpChallenge(
  key: string,
  fingerprint: string
): Promise<OtpVerificationResult> {
  if (
    !key.startsWith(`${config.redisPrefix}:challenge:`) ||
    !/^[a-f0-9]{64}$/.test(fingerprint)
  ) {
    return "unavailable";
  }

  const response = await executeRecommendationOtpScript(
    VERIFY_CHALLENGE_SCRIPT,
    [key],
    [fingerprint, String(config.maxAttempts)]
  );

  if (!response.ok) return "unavailable";

  switch (response.result) {
    case 1:
      return "verified";
    case 0:
      return "incorrect";
    case -1:
      return "expired";
    case -2:
      return "locked";
    default:
      return "unavailable";
  }
}
